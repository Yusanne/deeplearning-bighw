#!/usr/bin/env python
"""S9: CSV -> LaTeX booktabs table. Report numbers are never hand-typed.

Usage: python -I s9_csv_to_latex.py <in.csv> <out.tex> [--bold-max]
CSV: first column = row label; numeric columns auto-formatted (3 sig decimals kept).
"""
import csv
import sys


def is_num(x):
    try:
        float(x)
        return True
    except Exception:
        return False


def fmt(x):
    v = float(x)
    if abs(v - round(v)) < 1e-9:
        return str(int(round(v)))
    return f"{v:.3f}".rstrip("0").rstrip(".")


def main(inp, outp, bold_max=False):
    rows = list(csv.reader(open(inp, encoding="utf-8-sig")))
    hdr, body = rows[0], rows[1:]
    ncols = len(hdr)
    # bold the column max among numeric cells
    bold = set()
    if bold_max:
        for c in range(1, ncols):
            vals = [(r[c], float(r[c])) for r in body if len(r) > c and is_num(r[c])]
            if vals:
                mx = max(v for _, v in vals)
                bold |= {(i, c) for i, (_, v) in enumerate(vals) if v == mx}
    lines = ["% auto-generated by s9_csv_to_latex.py — do not hand-edit numbers",
             "\\begin{tabular}{" + "l" * 1 + "r" * (ncols - 1) + "}",
             "\\toprule",
             " & ".join(hdr) + " \\\\",
             "\\midrule"]
    for i, r in enumerate(body):
        cells = []
        for c, cell in enumerate(r[:ncols]):
            cell = cell.strip()
            if c > 0 and is_num(cell):
                cell = fmt(cell)
                if (i, c) in bold:
                    cell = "\\textbf{" + cell + "}"
            cells.append(cell)
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    open(outp, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"wrote {outp} ({len(body)} rows x {ncols - 1} numeric cols)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], "--bold-max" in sys.argv)
